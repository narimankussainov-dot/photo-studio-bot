# Функция кодирования картинки
def encode_image(image_path):
    with open(image_path, "rb") as image_file:
        return base64.b64encode(image_file.read()).decode('utf-8')


# 1. Обработка текста
# Добавляем словарь для хранения истории пользователей прямо под STUDIO_PROMPT
user_histories = {}

# ОБНОВЛЕННАЯ ФУНКЦИЯ: Теперь она принимает еще и user_id
async def process_text_with_ai(user_id: int, user_text: str, tg_username: str = "") -> str:
    try:
        # 1. Если пользователь пишет впервые, создаем ему чистую историю с системным промптом
        if user_id not in user_histories:
            user_histories[user_id] = [{"role": "system", "content": STUDIO_PROMPT}]

        # 2. Добавляем новое сообщение пользователя в его историю
        user_histories[user_id].append({"role": "user", "content": user_text})

        # 3. Чтобы не тратить лишние деньги (токены), берем промпт + только последние 10 сообщений
        messages_to_send = [user_histories[user_id][0]] + user_histories[user_id][-10:]

        response = await openai_client.chat.completions.create(
            model="gpt-5.4-mini",  # Используем самую новую модель
            messages=messages_to_send
        )

        bot_reply = response.choices[0].message.content

        # 1. Сохраняем ПОЛНЫЙ ответ (с тегом) в историю, чтобы бот помнил свой этап
        user_histories[user_id].append({"role": "assistant", "content": bot_reply})

        # 2. Вырезаем технический тег для клиента с помощью регулярного выражения
        # Это удалит текст вроде "[Текущий этап: 3]" или "[Текущий этап: 3]: " в начале
        clean_reply = re.sub(r'\[Текущий этап: \d+\]:?\s*', '', bot_reply)

        # Проверяем, перешел ли бот на финальный 7 этап
        if "[Текущий этап: 7]" in bot_reply:
            # Запускаем сбор данных в фоне (не заставляя клиента ждать)
            import asyncio
            asyncio.create_task(extract_lead_data(user_id, tg_username))

        return clean_reply

    except Exception as e:
        logging.error(f"Ошибка ИИ (текст): {e}")
        return "❌ Ошибка при обработке текста."


# 2. Обработка аудио
async def process_audio_with_ai(file_path: str) -> str:
    try:
        with open(file_path, "rb") as audio_file:
            transcript = await openai_client.audio.transcriptions.create(
                model="whisper-1",
                file=audio_file
            )
        raw_text = transcript.text
        return await process_text_with_ai(raw_text)  # Отправляем расшифрованный текст в функцию выше
    except Exception as e:
        logging.error(f"Ошибка ИИ (аудио): {e}")
        return "❌ Ошибка при обработке аудио."
    finally:
        if os.path.exists(file_path):
            os.remove(file_path)


# 3. НОВОЕ: Обработка фото
async def process_image_with_ai(image_path: str, caption: str = "") -> str:
    try:
        base64_image = encode_image(image_path)
        user_message = caption if caption else "Посмотри на этот референс для фотосессии. Что скажешь?"

        response = await openai_client.chat.completions.create(
            model="gpt-5-mini",
            messages=[
                {"role": "system", "content": STUDIO_PROMPT},
                {
                    "role": "user",
                    "content": [
                        {"type": "text", "text": user_message},
                        {"type": "image_url", "image_url": {"url": f"data:image/jpeg;base64,{base64_image}"}}
                    ]
                }
            ]
        )
        return response.choices[0].message.content
    except Exception as e:
        logging.error(f"Ошибка ИИ (фото): {e}")
        return "❌ Ошибка при анализе фотографии."
    finally:
        if os.path.exists(image_path):
            os.remove(image_path)


def reset_user_history(user_id: int):
    """Очищает историю переписки для конкретного пользователя"""
    if user_id in user_histories:
        del user_histories[user_id]


# --- ДОБАВЛЯЕМ НОВУЮ ФУНКЦИЮ ДЛЯ СБОРА АНКЕТЫ ---
async def extract_lead_data(user_id: int, tg_username: str):
    """Анализирует историю диалога и вытаскивает данные в JSON"""
    if user_id not in user_histories:
        return

    history = user_histories[user_id]

    extraction_prompt = (
        "Проанализируй этот диалог с клиентом фотостудии. "
        "Вытащи данные и верни ИХ СТРОГО В ФОРМАТЕ JSON без лишнего текста. "
        "Ключи JSON: name, city, school, class_num, students_count, decision_maker, format. "
        "Если данных нет, пиши '-'. "
        "Пример: {\"name\": \"Анна\", \"city\": \"Алматы\", \"school\": \"15\", \"class_num\": \"11А\", \"students_count\": \"20\", \"decision_maker\": \"родители\", \"format\": \"WhatsApp\"}"
    )

    messages_to_send = history + [{"role": "system", "content": extraction_prompt}]

    try:
        response = await openai_client.chat.completions.create(
            model="gpt-5.4-mini",
            response_format={"type": "json_object"},  # ЗАСТАВЛЯЕМ ИИ ОТДАТЬ СТРОГИЙ JSON
            messages=messages_to_send
        )

        # Превращаем текст от ИИ в словарь Python
        data = json.loads(response.choices[0].message.content)
        data['tg_username'] = f"@{tg_username}"  # Добавляем юзернейм

        # Отправляем в Гугл Таблицу!
        append_to_sheet(data)

    except Exception as e:
        print(f"Ошибка извлечения данных: {e}")